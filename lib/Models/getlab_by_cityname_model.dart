class GetLabByCityNameModel {
  List<Datum>? data;
  int? status;
  String? msg;

  GetLabByCityNameModel({
    this.data,
    this.status,
    this.msg,
  });

  factory GetLabByCityNameModel.fromJson(Map<String, dynamic> json) =>
      GetLabByCityNameModel(
        data: json["data"] == null
            ? []
            : List<Datum>.from(json["data"]!.map((x) => Datum.fromJson(x))),
        status: json["status"],
        msg: json["msg"],
      );

  Map<String, dynamic> toJson() => {
        "data": data == null
            ? []
            : List<dynamic>.from(data!.map((x) => x.toJson())),
        "status": status,
        "msg": msg,
      };
}

class Datum {
  int? id;
  String? name;

  Datum({
    this.id,
    this.name,
  });

  factory Datum.fromJson(Map<String, dynamic> json) => Datum(
        id: json["id"],
        name: json["name"],
      );

  Map<String, dynamic> toJson() => {
        "id": id,
        "name": name,
      };
}
